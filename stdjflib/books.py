def palmdb_bytes(title: str, creator: str) -> bytes:
    """A PalmDB header, which is what a `.mobi` and an `.azw3` both are.

    Deliberately a header and nothing else: the point of these fixtures is
    that Jellyfin *catalogues* them — `BookResolver` accepts the extension and
    hands back an ordinary Book with metadata and artwork — while no client
    can open one. Nothing in the server parses a byte of the content, so a
    real book inside would test nothing that this does not.

    It is a genuine PalmDB header rather than arbitrary bytes so that the file
    is at least structurally what its extension claims. Anything that tries to
    read further will find no records and should say so, which is the honest
    outcome for a file that exists to have no reader.
    """
    name = title.encode("ascii", "replace")[:31].ljust(32, b"\x00")
    header = bytearray(name)
    header += (0).to_bytes(2, "big")     # attributes
    header += (0).to_bytes(2, "big")     # version
    # PalmDB times are seconds since 1904. Fixed, not "now" — see EPOCH.
    stamp = (2020 - 1904) * 365 * 24 * 3600
    header += stamp.to_bytes(4, "big")   # creation date
    header += stamp.to_bytes(4, "big")   # modification date
    header += (0).to_bytes(4, "big")     # last backup
    header += (0).to_bytes(4, "big")     # modification number
    header += (0).to_bytes(4, "big")     # app info id
    header += (0).to_bytes(4, "big")     # sort info id
    header += b"BOOK"                    # type
    header += b"MOBI"                    # creator
    header += (0).to_bytes(4, "big")     # unique id seed
    header += (0).to_bytes(4, "big")     # next record list id
    header += (0).to_bytes(2, "big")     # number of records
    trailer = (f"stdjflib placeholder. {title}, by {creator}. "
               f"This file has a valid PalmDB header and no book inside: "
               f"Jellyfin catalogues it and no client can open it, which is "
               f"the case it exists to cover.\n").encode("utf-8")
    return bytes(header) + trailer


def write_palmdb(path: str, title: str, creator: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(palmdb_bytes(title, creator))



def write_cbz(path: str, pages: list[tuple[str, str]], *,
              comment: bytes | None = None,
              extra: dict[str, str] | None = None) -> None:
    """A comic archive: a zip of images, which is all a CBZ is.

    `pages` is (name-in-archive, path-on-disk); `extra` adds text members such
    as an internal `ComicInfo.xml`; `comment` is the zip's *archive* comment,
    which is where the ComicBookInfo dialect lives.

    Stored rather than deflated, matching what comic archives are in the wild —
    the pages are JPEG and already compressed, so deflating them buys nothing
    and costs a scan every time something opens the file.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_STORED) as zf:
        for name, source in pages:
            # Not `zf.write(source, name)`: that takes the entry's timestamp
            # from the file on disk, so the archive would differ between two
            # builds of an identical library.
            with open(source, "rb") as fh:
                zf.writestr(_member(name, zipfile.ZIP_STORED), fh.read())
        for name, text in (extra or {}).items():
            zf.writestr(_member(name, zipfile.ZIP_STORED), text)
        if comment is not None:
            zf.comment = comment


def write_cbt(path: str, pages: list[tuple[str, str]], *,
              extra: dict[str, str] | None = None) -> None:
    """A comic archive as a tar, which is what `.cbt` is.

    Jellyfin reads `.cb7`, `.cbr`, `.cbt` and `.cbz` through SharpCompress, so
    a tar gets a cover and a page count exactly as a zip does — but the two
    metadata providers that read *inside* an archive are hard-restricted to
    `.cbz`, so the `ComicInfo.xml` this puts in is deliberately never read.
    That is the fixture: the same bytes in a `.cbz` are metadata and here are
    a page.

    `.cbt` rather than `.cbr` because a RAR cannot be written from the
    standard library and this can. It answers the same question.
    """
    import io
    import tarfile

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with tarfile.open(path, "w") as tf:
        for name, source in pages:
            info = tarfile.TarInfo(name)
            info.size = os.path.getsize(source)
            # Not the file's mtime: a tar records it, so the archive would
            # differ between two builds of the same library.
            info.mtime = 0
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            with open(source, "rb") as fh:
                tf.addfile(info, fh)
        for name, text in (extra or {}).items():
            data = text.encode("utf-8")
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = 0
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tf.addfile(info, io.BytesIO(data))


def comicinfo_xml(*, title: str, series: str, number: int, year: int,
                  summary: str, publisher: str, genres: list[str],
                  writer: str, penciller: str = "", colourist: str = "",
                  language: str = "en") -> str:
    """The ComicRack `ComicInfo.xml` dialect, as `ComicInfoReader` reads it.

    Only the elements the server has an XPath for are written. It reads
    Title, Series, Number, Summary, Year/Month/Day, Genre (comma split),
    Publisher, LanguageISO and Manga, plus the people — and `Colourist` is
    spelled the British way in the server, which is the kind of detail a
    fixture exists to pin.
    """
    def esc(text: str) -> str:
        return (str(text).replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;"))

    rows = [
        ("Title", title), ("Series", series), ("Number", number),
        ("Summary", summary), ("Year", year), ("Month", 1), ("Day", 1),
        ("Genre", ", ".join(genres)), ("Publisher", publisher),
        ("Writer", writer), ("Penciller", penciller),
        ("Colourist", colourist), ("LanguageISO", language),
    ]
    body = "".join(f"  <{tag}>{esc(value)}</{tag}>\n"
                   for tag, value in rows if value != "")
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<ComicInfo xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
            'xmlns:xsd="http://www.w3.org/2001/XMLSchema">\n'
            f'{body}</ComicInfo>\n')


def comicbookinfo_json(*, title: str, series: str, issue: int, year: int,
                       month: int, publisher: str, genre: str, comments: str,
                       credits: list[tuple[str, str]], tags: list[str],
                       language: str = "en") -> bytes:
    """The ComicBookInfo dialect, which lives in the zip's *archive comment*.

    A zip comment is a free-text trailer nothing else looks at, which is why
    this convention could be bolted onto an existing format at all — and why
    it is invisible to anything that only lists entries. The server reads it
    with `JsonSerializer` into `ComicBookInfoFormat`, so the container key has
    to be spelled exactly `ComicBookInfo/1.0`.

    `credits` is (person, role); the role is parsed with
    `Enum.TryParse<PersonKind>`, so an unrecognised one silently becomes
    `Unknown` rather than failing.
    """
    payload = {
        "appID": "stdjflib/1.0",
        # Not "now": a wall-clock stamp here would make two builds of the same
        # library differ, which is the one thing this tool must never do.
        "lastModified": "2020-01-01 00:00:00 +0000",
        "ComicBookInfo/1.0": {
            "series": series,
            "title": title,
            "issue": issue,
            "publisher": publisher,
            "publicationMonth": month,
            "publicationYear": year,
            "genre": genre,
            "language": language,
            "comments": comments,
            "credits": [{"person": person, "role": role}
                        for person, role in credits],
            "tags": tags,
        },
    }
    return json.dumps(payload, ensure_ascii=False,
                      separators=(",", ":")).encode("utf-8")



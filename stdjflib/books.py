# What `ComicImageProvider` will open, and what it will accept as a page.
ARCHIVE_EXTENSIONS = (".cb7", ".cbr", ".cbt", ".cbz")
COVER_EXTENSIONS = (".png", ".jpeg", ".jpg", ".webp", ".bmp", ".gif")


def archive_entries(path: str) -> list[str] | None:
    """Every non-directory entry in a comic archive, or None if unreadable.

    The count matters because it *is* the page count: `ProbeProvider` stores
    `archive.Entries.Count(e => !e.IsDirectory) * 10000` as `RunTimeTicks`,
    counting a `ComicInfo.xml` as cheerfully as a page.
    """
    import tarfile

    try:
        if path.lower().endswith(".cbz"):
            with zipfile.ZipFile(path) as zf:
                return [i.filename for i in zf.infolist() if not i.is_dir()]
        if path.lower().endswith(".cbt"):
            with tarfile.open(path) as tf:
                return [m.name for m in tf.getmembers() if not m.isdir()]
    except (OSError, zipfile.BadZipFile, tarfile.TarError):
        return None
    return None


def archive_cover(names: list[str]) -> str | None:
    """Which entry Jellyfin would use as the cover.

    `ComicImageProvider.FindCoverEntryInArchiveAsync`, restated rather than
    called: an entry named exactly `cover.<ext>` — tried in the order below,
    which puts `.png` ahead of `.jpg` — and otherwise the alphabetically first
    entry by full key that has an image extension. Both halves matter: the
    exact match takes no path prefix and is case-sensitive, so `Cover.jpg` and
    `images/cover.jpg` both fall through to the sort.
    """
    for ext in COVER_EXTENSIONS:
        if "cover" + ext in names:
            return "cover" + ext
    for name in sorted(names):
        if os.path.splitext(name)[1].lower() in COVER_EXTENSIONS:
            return name
    return None
